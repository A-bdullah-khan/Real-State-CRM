def env_bool(name, default=False):
    return os.getenv(name, str(default)).strip().lower() in {"1", "true", "yes", "on"}


def env_list(name, default=""):
    # A blank value (e.g. `CSRF_TRUSTED_ORIGINS=`) falls back to the default, same as unset.
    return [item.strip() for item in (os.getenv(name) or default).split(",") if item.strip()]


def env_origins(name, default=""):
    # Browsers send Origin without a trailing slash; a stray "/" in .env would never match
    # (and django-cors-headers rejects it outright), so normalise it away.
    return [origin.rstrip("/") for origin in env_list(name, default)]


